

create table if not exists enkazlar (
  id bigint generated by default as identity primary key,
  isim text,
  enlem float,
  boylam float,
  talep float,
  durum text default 'aktif',
  makine_gerekli int default 0
);

create table if not exists ekipler (
  id bigint generated by default as identity primary key,
  isim text,
  tip text,
  kapasite float,
  durum text default 'musait',
  erisim_kodu text
);

-- Mevcut kurulum: create table if not exists sütun eklemez.
-- Kod boş bırakılan ekip kaydı bu sütun olmadan da yazılır; kod doluysa sütun gerekir.
alter table ekipler add column if not exists erisim_kodu text;

create table if not exists atamalar (
  id bigint generated by default as identity primary key,
  ekip_id bigint references ekipler(id),
  enkaz_id bigint references enkazlar(id),
  baslangic text,
  bitis text,
  durum text default 'devam'
);

create table if not exists yardimci_kaynaklar (
  id bigint generated by default as identity primary key,
  enkaz_id bigint references enkazlar(id),
  umke_sayisi int default 0,
  makine_sayisi int default 0
);

-- Plan anlık görüntüsü. Atama satırları atamalar tablosunda kalır.
-- ozet, açık merkezleri ve ekip yerleşimini taşır; operasyonel yeniden çözüm onu okur.
create table if not exists planlar (
  id bigint generated by default as identity primary key,
  olusturma text,
  durum text,
  periyot_sayisi int,
  sure_sinir int,
  z1 float,
  alt_sinir float,
  aralik float,
  acik_merkezler text,
  ozet text
);


alter table enkazlar enable row level security;
alter table ekipler enable row level security;
alter table atamalar enable row level security;
alter table yardimci_kaynaklar enable row level security;
alter table planlar enable row level security;

create policy "public all" on enkazlar for all using (true);
create policy "public all" on ekipler for all using (true);
create policy "public all" on atamalar for all using (true);
create policy "public all" on yardimci_kaynaklar for all using (true);

-- create policy ikinci kez hata verir. Yalnızca planlar için tekrar çalıştırılabilir.
do $$
begin
  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'planlar' and policyname = 'public all'
  ) then
    create policy "public all" on planlar for all using (true);
  end if;
end $$;
